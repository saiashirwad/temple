// Lays out the forest river: its axis through the path's crossing, and its water level along
// that axis, following the valley floor down and never rising. Writes src/generated/river.gen.ts.
//
//   npx tsx tools/river/make.ts
import { writeFileSync } from 'node:fs';
import { landAt } from '../../src/world/terrain.ts';
import { trailAt } from '../../src/world/trail/trail.ts';
import { meander } from '../../src/world/trail/river.ts';

const ALONG = 520;
const ANGLE = (140 * Math.PI) / 180;
const L = 240;
const STEP = 4;
const c = trailAt(ALONG);
const u = [Math.cos(ANGLE), Math.sin(ANGLE)] as const;

const at = (s: number, v: number) => {
  const o = meander(s) + v;

  return [c.x + u[0] * s - u[1] * o, c.z + u[1] * s + u[0] * o] as const;
};

const floor: number[] = [];

for (let s = -L; s <= L + 0.01; s += STEP) {
  let m = Infinity;

  for (const v of [-6, -3, 0, 3, 6]) m = Math.min(m, landAt(...at(s, v)));
  floor.push(m);
}

// Falling at least 1 in 100 downstream, a metre below the valley floor
let level = Infinity;
const raw = floor.map((h) => (level = Math.min(level - 0.01 * STEP, h - 1.0)));

// Smoothed, without rising above the raw level anywhere
let out = raw;

for (let pass = 0; pass < 3; pass++) out = out.map((_, i) => (out[Math.max(i - 1, 0)]! + out[i]! * 2 + out[Math.min(i + 1, out.length - 1)]!) / 4);

out = out.map((v, i) => Math.min(v, raw[i]!));

for (let i = 1; i < out.length; i++) out[i] = Math.min(out[i]!, out[i - 1]! - 0.005);

const mid = (out.length - 1) / 2;

console.log('depth at the crossing', (landAt(c.x, c.z) - out[mid]!).toFixed(2), 'drop', (out[0]! - out[out.length - 1]!).toFixed(1));

console.log('deepest cut', Math.max(...floor.map((h, i) => h - out[i]!)).toFixed(1));

writeFileSync(
  new URL('../../src/generated/river.gen.ts', import.meta.url),
  `// Generated by tools/river/make.ts.
export const RIVER = { c: [${c.x.toFixed(2)}, ${c.z.toFixed(2)}] as const, u: [${u[0].toFixed(5)}, ${u[1].toFixed(5)}] as const, length: ${L}, step: ${STEP} } as const;
export const RIVER_LEVEL: readonly number[] = [${out.map((v) => v.toFixed(2)).join(', ')}];
`,
);
